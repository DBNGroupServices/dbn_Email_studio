/* Writes addin/manifest.xml for a given hosting address.
   Usage: node addin-build/make-manifest.js [baseUrl]
   Default base: https://dbngroupservices.github.io/dbn_Email_studio/ */
const fs=require('fs'),path=require('path');
const base=(process.argv[2]||'https://dbngroupservices.github.io/dbn_Email_studio/').replace(/\/?$/,'/');
const u=new URL(base);if(u.protocol!=='https:')throw new Error('The add-in must be hosted on HTTPS.');
const origin=u.origin;
const esc=s=>s.replace(/&/g,'&amp;').replace(/"/g,'&quot;');
const B=esc(base);
function surface(kind,gid,cid,pin){
  return `          <ExtensionPoint xsi:type="${kind}">
            <OfficeTab id="TabDefault">
              <Group id="${gid}">
                <Label resid="Group.Label"/>
                <Control xsi:type="Button" id="${cid}">
                  <Label resid="Button.Label"/>
                  <Supertip><Title resid="Button.Label"/><Description resid="Button.Description"/></Supertip>
                  <Icon><bt:Image size="16" resid="Icon.16"/><bt:Image size="32" resid="Icon.32"/><bt:Image size="80" resid="Icon.80"/></Icon>
                  <Action xsi:type="ShowTaskpane"><SourceLocation resid="Pane.Url"/>${pin?'<SupportsPinning>true</SupportsPinning>':''}</Action>
                </Control>
              </Group>
            </OfficeTab>
          </ExtensionPoint>`;
}
const hosts=pin=>`      <Hosts>
        <Host xsi:type="MailHost">
          <DesktopFormFactor>
            <FunctionFile resid="Commands.Url"/>
${surface('MessageReadCommandSurface','DBN.Read.Group','DBN.Read.Open',pin)}
${surface('MessageComposeCommandSurface','DBN.Compose.Group','DBN.Compose.Open',false)}
          </DesktopFormFactor>
        </Host>
      </Hosts>`;
const resources=`      <Resources>
        <bt:Images>
          <bt:Image id="Icon.16" DefaultValue="${B}icons/assistant-16.png"/>
          <bt:Image id="Icon.32" DefaultValue="${B}icons/assistant-32.png"/>
          <bt:Image id="Icon.80" DefaultValue="${B}icons/assistant-80.png"/>
        </bt:Images>
        <bt:Urls>
          <bt:Url id="Commands.Url" DefaultValue="${B}commands.html"/>
          <bt:Url id="Pane.Url" DefaultValue="${B}taskpane.html"/>
        </bt:Urls>
        <bt:ShortStrings>
          <bt:String id="Group.Label" DefaultValue="Bulwark HQ"/>
          <bt:String id="Button.Label" DefaultValue="Assistant"/>
        </bt:ShortStrings>
        <bt:LongStrings>
          <bt:String id="Button.Description" DefaultValue="Suggested replies, dictation and one-box drafting in your voice with Claude. Pin the pane to keep it open as you move between emails."/>
        </bt:LongStrings>
      </Resources>`;
const xml=`<?xml version="1.0" encoding="UTF-8"?>
<!-- Bulwark HQ Assistant 3.2 - Outlook add-in manifest. Generated by addin-build/make-manifest.js.
     Hosted at ${B} - no desktop app or local server is needed. -->
<OfficeApp xmlns="http://schemas.microsoft.com/office/appforoffice/1.1"
           xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
           xmlns:bt="http://schemas.microsoft.com/office/officeappbasictypes/1.0"
           xsi:type="MailApp">
  <Id>7877fe62-01f2-4af8-b073-dfa805099a63</Id>
  <Version>3.2.0.0</Version>
  <ProviderName>Bulwark HQ</ProviderName>
  <DefaultLocale>en-AU</DefaultLocale>
  <DisplayName DefaultValue="Bulwark HQ Assistant"/>
  <Description DefaultValue="Reply in your own voice, rewrite, summarise and proofread emails with Claude. Runs inside Outlook; no desktop app needed."/>
  <IconUrl DefaultValue="${B}icons/assistant-64.png"/>
  <HighResolutionIconUrl DefaultValue="${B}icons/assistant-128.png"/>
  <SupportUrl DefaultValue="${B}help.html"/>
  <AppDomains>
    <AppDomain>${esc(origin)}</AppDomain>
  </AppDomains>
  <Hosts>
    <Host Name="Mailbox"/>
  </Hosts>
  <Requirements>
    <Sets>
      <Set Name="Mailbox" MinVersion="1.3"/>
    </Sets>
  </Requirements>
  <FormSettings>
    <Form xsi:type="ItemRead">
      <DesktopSettings>
        <SourceLocation DefaultValue="${B}taskpane.html"/>
        <RequestedHeight>450</RequestedHeight>
      </DesktopSettings>
    </Form>
  </FormSettings>
  <Permissions>ReadWriteItem</Permissions>
  <Rule xsi:type="RuleCollection" Mode="Or">
    <Rule xsi:type="ItemIs" ItemType="Message" FormType="Read"/>
    <Rule xsi:type="ItemIs" ItemType="Message" FormType="Edit"/>
  </Rule>
  <DisableEntityHighlighting>false</DisableEntityHighlighting>
  <VersionOverrides xmlns="http://schemas.microsoft.com/office/mailappversionoverrides" xsi:type="VersionOverridesV1_0">
    <Requirements>
      <bt:Sets DefaultMinVersion="1.3">
        <bt:Set Name="Mailbox"/>
      </bt:Sets>
    </Requirements>
${hosts(false)}
${resources}
    <!-- Mailbox 1.5+ (current Outlook Classic): pinnable pane that follows the selected email. -->
    <VersionOverrides xmlns="http://schemas.microsoft.com/office/mailappversionoverrides/1.1" xsi:type="VersionOverridesV1_1">
      <Requirements>
        <bt:Sets DefaultMinVersion="1.5">
          <bt:Set Name="Mailbox"/>
        </bt:Sets>
      </Requirements>
${hosts(true)}
${resources}
    </VersionOverrides>
  </VersionOverrides>
</OfficeApp>
`;
fs.writeFileSync(path.join(__dirname,'..','addin','manifest.xml'),xml);
console.log('Wrote addin/manifest.xml for '+base);
